DROP TABLE IF EXISTS temperature_record;
DROP TABLE IF EXISTS temperature_unit;

CREATE TABLE IF NOT EXISTS unit (
    unit_id INT PRIMARY KEY,
    unit_key VARCHAR(50) NOT NULL UNIQUE,
    category VARCHAR(20) NOT NULL,
    symbol VARCHAR(10) NOT NULL,
    factor_to_base DOUBLE NOT NULL,
    offset_to_base DOUBLE NOT NULL DEFAULT 0,
    display_order INT NOT NULL
);

CREATE TABLE IF NOT EXISTS unit_translation (
    unit_id INT NOT NULL,
    lang VARCHAR(5) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    PRIMARY KEY (unit_id, lang),
    CONSTRAINT fk_unit_translation_unit
        FOREIGN KEY (unit_id) REFERENCES unit(unit_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS conversion_history (
    conversion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    input_value DOUBLE NOT NULL,
    from_unit_id INT NOT NULL,
    to_unit_id INT NOT NULL,
    result_value DOUBLE NOT NULL,
    language_code VARCHAR(5) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_conversion_from
        FOREIGN KEY (from_unit_id) REFERENCES unit(unit_id),
    CONSTRAINT fk_conversion_to
        FOREIGN KEY (to_unit_id) REFERENCES unit(unit_id)
);

CREATE TABLE IF NOT EXISTS distance_measurement (
    distance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    measurement_value DOUBLE NOT NULL,
    unit_id INT NOT NULL,
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_distance_unit
        FOREIGN KEY (unit_id) REFERENCES unit(unit_id)
);

CREATE TABLE IF NOT EXISTS time_measurement (
    time_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    measurement_value DOUBLE NOT NULL,
    unit_id INT NOT NULL,
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_time_unit
        FOREIGN KEY (unit_id) REFERENCES unit(unit_id)
);

CREATE TABLE IF NOT EXISTS speed_measurement (
    speed_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distance_id BIGINT NOT NULL,
    time_id BIGINT NOT NULL,
    speed_value DOUBLE NOT NULL,
    speed_unit_id INT NOT NULL,
    language_code VARCHAR(5) NOT NULL,
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_speed_distance
        FOREIGN KEY (distance_id) REFERENCES distance_measurement(distance_id),
    CONSTRAINT fk_speed_time
        FOREIGN KEY (time_id) REFERENCES time_measurement(time_id),
    CONSTRAINT fk_speed_unit
        FOREIGN KEY (speed_unit_id) REFERENCES unit(unit_id)
);

